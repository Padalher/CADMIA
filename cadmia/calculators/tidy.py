"""Move accessory engine byproducts into an ``aux/`` subfolder to reduce clutter.

An ORCA (or Gaussian) run leaves the essentials — ``.inp``/``.out``/``.gbw`` and,
for density plots, ``.densities``/``.densitiesinfo`` — alongside a handful of
accessory files (autogenerated citations, the property dump, CHELPG charge/potential
files, the rewritten geometry). None of the accessory files are read by CADMIA, so
they are moved into ``<dir>/aux/`` after a job completes. The files CADMIA and
``orca_plot`` need are deliberately left in place.
"""
from __future__ import annotations

from pathlib import Path
from typing import List

# Suffixes appended to a job's stem that are safe to tuck away. NOTE: .densities /
# .densitiesinfo are intentionally absent — orca_plot reads the density from them.
AUX_SUFFIXES = (
    ".bibtex",        # ORCA 6 autogenerated method citations
    ".property.txt",  # ORCA structured property dump (redundant with .out)
    ".chelpg.xyz",    # CHELPG charges as an xyz-like file
    ".pc_chelpg",     # CHELPG point charges
    ".vpot",          # electrostatic potential on the CHELPG grid points
    ".xyz",           # engine-rewritten geometry
)


def tidy_job_outputs(directory: "str | Path", stem: str, aux_subdir: str = "aux") -> List[str]:
    """Move ``<stem><suffix>`` accessory files from *directory* into *aux_subdir*.

    Returns the list of filenames moved. Missing files are skipped; the ``aux/``
    folder is only created if there is something to move.
    """
    d = Path(directory)
    dest = d / aux_subdir
    inp = d / f"{stem}.inp"
    moved: List[str] = []
    for suffix in AUX_SUFFIXES:
        f = d / f"{stem}{suffix}"
        if not f.is_file():
            continue
        if suffix == ".xyz" and not _written_by_the_engine(f, inp):
            # <stem>.xyz is a byproduct only when the ENGINE rewrote it, which it does for an
            # optimization. In a single point or a frequency job the file of that name is the
            # geometry the user supplied, and tucking it into aux/ takes it out of the
            # directory `prepare` rescans.
            continue
        dest.mkdir(exist_ok=True)
        f.rename(dest / f.name)
        moved.append(f.name)
    return moved


def _written_by_the_engine(xyz: Path, inp: Path) -> bool:
    """True when the .xyz is newer than the input, i.e. the engine produced it."""
    try:
        return xyz.stat().st_mtime > inp.stat().st_mtime
    except OSError:
        return False          # no input to compare against: leave the file alone


def slurm_tidy_block(remote_input: str, work_dir: str, aux_subdir: str = "aux") -> str:
    """Shell snippet that tidies a job's accessory files on the compute node.

    Appended to the SLURM script AFTER the completion marker so it never masks the
    engine's exit status. *remote_input* names the job (its stem is reused).
    """
    stem = Path(remote_input).stem
    exts = " ".join(AUX_SUFFIXES)
    return (
        f'for _ext in {exts}; do\n'
        f'  [ -f "{work_dir}/{stem}$_ext" ] && '
        f'mkdir -p "{work_dir}/{aux_subdir}" && '
        f'mv "{work_dir}/{stem}$_ext" "{work_dir}/{aux_subdir}/"\n'
        f'done'
    )
