"""Generate a VMD/Tachyon script to render a .cube field (publication-quality figures).

This reproduces the classic Multiwfn → VMD → Tachyon workflow without a GUI click-through:
the script loads the cube (geometry + volume), draws the atoms plus one or two isosurfaces
(±isovalue for signed fields such as orbitals/MEP), sets clean display options, and exposes
a ``render_hires`` proc that renders at high resolution.

No Python dependency: it only writes a .tcl text file. VMD itself does the rendering.
By default it uses VMD's built-in TachyonInternal renderer (no external binary or path
needed); pass an explicit tachyon executable to emit the external-Tachyon command instead.
"""
from __future__ import annotations

from pathlib import Path
from typing import Optional

from cadmia.core import VolumetricGrid

# VMD ColorID indices.
_COLOR_ID = {"blue": 0, "red": 1, "gray": 2, "orange": 3, "yellow": 4, "green": 7,
             "white": 8, "pink": 9, "cyan": 10, "purple": 11, "black": 16}

_TEMPLATE = """# VMD/Tachyon script generated by CADMIA for: {cube_name}
# Interactive:      vmd -e {script_name}
#   then rotate to taste and, in the VMD console, run:  render_hires
# Non-interactive:  vmd -dispdev text -e {script_name}   (uncomment the render_hires call below)

mol new {{{cube_path}}} type cube waitfor all

# ---- atoms ----
mol modstyle   0 0 CPK 1.0 0.3 12 12
mol modcolor   0 0 Element
mol modmaterial 0 0 Opaque
{orientation_line}
{iso_reps}
# ---- display ----
color Display Background white
display projection Orthographic
display depthcue on
display rendermode GLSL
axes location Off
display resize {width} {height}

# ---- high-resolution render ----
# {render_note}
proc render_hires {{ {{out "{render_output}"}} }} {{
{render_body}
    puts "CADMIA: rendered $out"
}}

puts "CADMIA: loaded {cube_name}. Rotate as desired, then run:  render_hires"
# render_hires   ;# <- uncomment for a one-shot non-interactive render
"""

_ISO_REP = """# ---- {label} lobe (iso = {iso_signed:g}) ----
mol addrep 0
mol modstyle   {rep} 0 Isosurface {iso_signed:g} 0 0 0 1 1
mol modcolor   {rep} 0 ColorID {color_id}
mol modmaterial {rep} 0 {material}
"""


def vmd_script(
    grid: VolumetricGrid,
    *,
    cube_path: "str | Path",
    script_name: str = "render.tcl",
    isovalue: Optional[float] = None,
    resolution: "tuple[int, int]" = (1920, 1440),
    pos_color: str = "blue",
    neg_color: str = "red",
    material: str = "Transparent",
    render_output: str = "render.tga",
    tachyon: Optional[str] = None,
    orientation=None,
) -> tuple[str, list]:
    """Build a VMD .tcl script for *grid* (read from *cube_path*).

    Returns (script_text, warnings). For signed fields two isosurfaces are emitted at
    ±isovalue; for positive fields a single one. isovalue defaults to 15% of the field's
    maximum absolute value (consistent with the HTML viewer). When *orientation* is given
    (from `cadmia view`), the script fixes the molecule's rotation so VMD opens in that pose.
    """
    warnings: list = []
    orientation_line = ""
    if orientation is not None and not getattr(orientation, "is_identity", False):
        from cadmia.structure.rendering.orientation import vmd_rotate_matrix
        orientation_line = ("\n# ---- orientation from cadmia view ----\n"
                            f"molinfo top set rotate_matrix {vmd_rotate_matrix(orientation)}\n")
    vmin, vmax = grid.vmin, grid.vmax
    max_abs = max(abs(vmin), abs(vmax))
    iso = isovalue if isovalue is not None else round(0.15 * max_abs, 6)
    if max_abs == 0:
        warnings.append("Field is uniformly zero; the isosurface will be empty.")
    width, height = int(resolution[0]), int(resolution[1])

    reps = []
    rep_idx = 1  # rep 0 is the atoms
    reps.append(_ISO_REP.format(label="positive", iso_signed=iso, rep=rep_idx,
                                color_id=_COLOR_ID.get(pos_color, 0), material=material))
    if vmin < -iso:
        rep_idx += 1
        reps.append(_ISO_REP.format(label="negative", iso_signed=-iso, rep=rep_idx,
                                    color_id=_COLOR_ID.get(neg_color, 1), material=material))

    if tachyon:
        render_note = f"External Tachyon: {tachyon}"
        render_body = (
            f'    render Tachyon $out.dat "{tachyon} -aasamples 12 $out.dat '
            f'-format TARGA -res {width} {height} -o $out"'
        )
    else:
        render_note = "Built-in renderer (no external binary needed)."
        render_body = "    render TachyonInternal $out"

    script = _TEMPLATE.format(
        cube_name=Path(cube_path).name,
        cube_path=str(Path(cube_path).resolve()),
        script_name=script_name,
        orientation_line=orientation_line,
        iso_reps="".join(reps),
        width=width, height=height,
        render_note=render_note,
        render_body=render_body,
        render_output=render_output,
    )
    return script, warnings


def write_vmd_script(
    source: "str | Path | VolumetricGrid",
    filepath: "str | Path",
    *,
    cube_path: "str | Path | None" = None,
    isovalue: Optional[float] = None,
    resolution: "tuple[int, int]" = (1920, 1440),
    material: str = "Transparent",
    render_output: str = "render.tga",
    tachyon: Optional[str] = None,
    field_type: str = "other",
) -> list:
    """Parse a .cube (or accept a VolumetricGrid) and write a VMD/Tachyon .tcl script.

    Returns the list of warnings. When *source* is already a grid, pass *cube_path* so the
    generated script points at the real cube file VMD must load.
    """
    if isinstance(source, VolumetricGrid):
        grid = source
        cube = cube_path or grid.source_file
        if not cube:
            raise ValueError("cube_path is required when passing a VolumetricGrid.")
    else:
        from cadmia.io.cube import parse_cube
        grid = parse_cube(source, field_type=field_type)
        cube = source
    script, warnings = vmd_script(
        grid, cube_path=cube, script_name=Path(filepath).name, isovalue=isovalue,
        resolution=resolution, material=material, render_output=render_output, tachyon=tachyon,
    )
    Path(filepath).write_text(script, encoding="utf-8")
    return warnings
